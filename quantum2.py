# 2. Load Evaluation Data & Define Baseline Configuration
df_final = pd.read_csv('final_72_comparison_table.csv')

# Local compute per client-round (t_comp = 450 ms as measured from your Flower testbed)
T_COMP_PER_CLIENT_ROUND = 0.450

# Target intrusion detection accuracy milestones (mapped to communication rounds)
CONVERGENCE_MILESTONES = {
    10: {'Accuracy': '95.0%', 'Label': 'Initial Threshold (95%)'},
    50: {'Accuracy': '98.2%', 'Label': 'Operational Target (98%)'},
    100: {'Accuracy': '99.4%', 'Label': 'Asymptotic Plateau (99.4%)'},
}

records = []

# 3. Calculate Wall-Clock Time-to-Convergence & Relative Penalties
for n_clients in sorted(df_final['Clients (N)'].unique()):
  for r_conv in sorted(df_final['Rounds (R)'].unique()):
    milestone = CONVERGENCE_MILESTONES.get(
        r_conv, {'Accuracy': 'N/A', 'Label': f'Round {r_conv}'}
    )

    # Filter data slice
    sub_slice = df_final[
        (df_final['Clients (N)'] == n_clients)
        & (df_final['Rounds (R)'] == r_conv)
    ]

    # Baseline K1 handshake latencies
    k1_off_hs = sub_slice[sub_slice['Config'] == 'K1']['Time OFF (s)'].values[0]
    k1_on_hs = sub_slice[sub_slice['Config'] == 'K1']['Time ON (s)'].values[0]

    t_comp_total = r_conv * T_COMP_PER_CLIENT_ROUND
    k1_ttc_off = t_comp_total + k1_off_hs
    k1_ttc_on = t_comp_total + k1_on_hs

    for cfg in ['K1', 'H1', 'H2', 'P1']:
      row = sub_slice[sub_slice['Config'] == cfg].iloc[0]

      hs_off = row['Time OFF (s)']
      hs_on = row['Time ON (s)']

      ttc_off = t_comp_total + hs_off
      ttc_on = t_comp_total + hs_on

      # Calculate Relative Time-to-Convergence Penalty (%) vs K1
      penalty_off = ((ttc_off - k1_ttc_off) / k1_ttc_off) * 100.0
      penalty_on = ((ttc_on - k1_ttc_on) / k1_ttc_on) * 100.0

      records.append({
          'Clients (N)': n_clients,
          'Convergence Round (R*)': r_conv,
          'Target Accuracy': milestone['Accuracy'],
          'Milestone': milestone['Label'],
          'Config': cfg,
          'Compute Time (s)': round(t_comp_total, 3),
          'Handshake Time OFF (s)': round(hs_off, 3),
          'Total TTC OFF (s)': round(ttc_off, 3),
          'TTC Penalty OFF (%)': round(penalty_off, 2),
          'Handshake Time ON (s)': round(hs_on, 3),
          'Total TTC ON (s)': round(ttc_on, 3),
          'TTC Penalty ON (%)': round(penalty_on, 2),
          'Wire Traffic OFF (KB)': round(row['Traffic OFF (KB)'], 2),
          'Wire Traffic ON (KB)': round(row['Traffic ON (KB)'], 2),
      })

df_ttc = pd.DataFrame(records)

# Save Master Evaluation Dataset
