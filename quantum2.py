def prepare_dataset(csv_path="friday.csv", num_clients=5, output_dir="./fl_data_5clients"):
    print("Cleaning dataset...")
    df = pd.read_csv(csv_path)
    df.columns = df.columns.str.strip()
    df.replace([np.inf, -np.inf], np.nan, inplace=True)
    df.dropna(inplace=True)

    # Drop non-predictive metadata columns
    drop_cols = ['Flow ID', 'Source IP', 'Source Port', 'Destination IP', 'Timestamp']
    df.drop(columns=[c for c in drop_cols if c in df.columns], inplace=True)

    X = df.drop(columns=['Label'])
    y = df['Label']

    label_encoder = LabelEncoder()
    y_encoded = label_encoder.fit_transform(y)

    X_train, X_test, y_train, y_test = train_test_split(
        X, y_encoded, test_size=0.20, random_state=42, stratify=y_encoded
    )

    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_test_scaled = scaler.transform(X_test)

    os.makedirs(output_dir, exist_ok=True)

    # Dynamic split across N clients
    X_splits = np.array_split(X_train_scaled, num_clients)
    y_splits = np.array_split(y_train, num_clients)

    for i in range(num_clients):
        np.savez_compressed(
            os.path.join(output_dir, f"client_{i+1}.npz"),
            x_train=X_splits[i],
            y_train=y_splits[i]
        )

    np.savez_compressed(os.path.join(output_dir, "global_test.npz"), x_test=X_test_scaled, y_test=y_test)
    print(f"✅ Success! Extracted {X_train_scaled.shape[1]} features across {num_clients} client partitions in '{output_dir}/'")

prepare_dataset("friday.csv", num_clients=5, output_dir="./fl_data_5clients")

