import socket
import ssl
import time

def benchmark_live_tls_connection(host: str, port: int, ca_file: str) -> dict:
    """
    Establishes an in-process TLS 1.3 socket to measure pure handshake latency
    and wire transfer size without shell/subprocess fork overhead.
    """
    ctx = ssl.create_default_context(cafile=ca_file)
    ctx.check_hostname = False

    raw_sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    tls_sock = ctx.wrap_socket(raw_sock, server_hostname=host)

    t0 = time.perf_counter()
    tls_sock.connect((host, port))
    t1 = time.perf_counter()

    handshake_ms = (t1 - t0) * 1000.0

    # Send a ping probe to register round-trip wire footprint
    tls_sock.sendall(b"PING\n")
    tls_sock.close()

    return {
        "handshake_ms": handshake_ms,
        "negotiated_cipher": tls_sock.cipher()
    }

